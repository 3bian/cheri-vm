pub const CAPABILITY_REGISTERS: [u16; 9] = [
    MACHINE_EXCEPTION_PROGRAM_COUNTER,
    MACHINE_SCRATCH,
    MACHINE_THREAD_IDENTIFIER,
    MACHINE_TRAP_VECTOR,
    SUPERVISOR_EXCEPTION_PROGRAM_COUNTER,
    SUPERVISOR_SCRATCH,
    SUPERVISOR_THREAD_IDENTIFIER,
    SUPERVISOR_TRAP_VECTOR,
    USER_THREAD_IDENTIFIER,
];

pub const MACHINE_EXCEPTION_PROGRAM_COUNTER: u16 = 0x341;
pub const MACHINE_SCRATCH: u16 = 0x340;
pub const MACHINE_THREAD_IDENTIFIER: u16 = 0x37f;
pub const MACHINE_TRAP_VECTOR: u16 = 0x305;
pub const SUPERVISOR_EXCEPTION_PROGRAM_COUNTER: u16 = 0x141;
pub const SUPERVISOR_SCRATCH: u16 = 0x140;
pub const SUPERVISOR_THREAD_IDENTIFIER: u16 = 0x17f;
